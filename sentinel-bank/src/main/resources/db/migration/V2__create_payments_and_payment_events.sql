CREATE TABLE payments (
    id UUID PRIMARY KEY,
    source_account_id BIGINT NOT NULL,
    created_by_user_id BIGINT NOT NULL,
    amount NUMERIC(18,2) NOT NULL,
    currency CHAR(3) NOT NULL,
    beneficiary_reference VARCHAR(100) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    approved_by_user_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_payments_source_account
        FOREIGN KEY (source_account_id)
        REFERENCES accounts(id),

    CONSTRAINT fk_payments_creator
        FOREIGN KEY (created_by_user_id)
        REFERENCES bank_users(id),

    CONSTRAINT fk_payments_approver
        FOREIGN KEY (approved_by_user_id)
        REFERENCES bank_users(id),

    CONSTRAINT chk_payments_amount
        CHECK (amount > 0),

    CONSTRAINT chk_payments_currency
        CHECK (currency ~ '^[A-Z]{3}$'),

    CONSTRAINT chk_payments_status
        CHECK (status IN ('PENDING', 'APPROVED', 'CANCELLED', 'COMPLETED'))
);

CREATE INDEX idx_payments_source_account_id
    ON payments(source_account_id);

CREATE INDEX idx_payments_created_by_user_id
    ON payments(created_by_user_id);

CREATE INDEX idx_payments_status
    ON payments(status);


CREATE TABLE payment_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id UUID NOT NULL,
    actor_user_id BIGINT,
    event_type VARCHAR(50) NOT NULL,
    from_status VARCHAR(20),
    to_status VARCHAR(20),
    details JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_payment_events_payment
        FOREIGN KEY (payment_id)
        REFERENCES payments(id),

    CONSTRAINT fk_payment_events_actor
        FOREIGN KEY (actor_user_id)
        REFERENCES bank_users(id),

    CONSTRAINT chk_payment_events_from_status
        CHECK (
            from_status IS NULL OR
            from_status IN ('PENDING', 'APPROVED', 'CANCELLED', 'COMPLETED')
        ),

    CONSTRAINT chk_payment_events_to_status
        CHECK (
            to_status IS NULL OR
            to_status IN ('PENDING', 'APPROVED', 'CANCELLED', 'COMPLETED')
        )
);

CREATE INDEX idx_payment_events_payment_id
    ON payment_events(payment_id);

CREATE INDEX idx_payment_events_actor_user_id
    ON payment_events(actor_user_id);