CREATE TABLE bank_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL,
    password_hash TEXT NOT NULL,
    role VARCHAR(20) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_bank_users_username UNIQUE (username),
    CONSTRAINT chk_bank_users_role
        CHECK (role IN ('CUSTOMER', 'ADMIN'))
);

CREATE TABLE accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number VARCHAR(34) NOT NULL,
    owner_user_id BIGINT NOT NULL,
    balance NUMERIC(18,2) NOT NULL DEFAULT 0,
    currency CHAR(3) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_accounts_account_number UNIQUE (account_number),

    CONSTRAINT fk_accounts_owner
        FOREIGN KEY (owner_user_id)
        REFERENCES bank_users(id),

    CONSTRAINT chk_accounts_balance
        CHECK (balance >= 0),

    CONSTRAINT chk_accounts_status
        CHECK (status IN ('ACTIVE', 'BLOCKED')),

    CONSTRAINT chk_accounts_currency
        CHECK (currency ~ '^[A-Z]{3}$')
);

CREATE INDEX idx_accounts_owner_user_id
    ON accounts(owner_user_id);